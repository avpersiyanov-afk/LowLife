from pyrevit import revit, EXEC_PARAMS

from lowlife import filter_selection

doc = revit.doc
uidoc = revit.uidoc
view = doc.ActiveView

try:
    config_mode = bool(EXEC_PARAMS.config_mode)
except Exception:
    config_mode = False


# ------------------------------------------------------------
# ОСНОВНОЙ СЦЕНАРИЙ
# ------------------------------------------------------------

if config_mode:
    filter_selection.configure(doc, view)
else:
    filter_selection.run(doc, uidoc, view)
